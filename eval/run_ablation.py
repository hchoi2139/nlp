class PCLModelAblation(nn.Module):
    def __init__(self, model_name="microsoft/deberta-v3-base"):
        super().__init__()
        self.deberta = AutoModel.from_pretrained(model_name)
        hidden_size = self.deberta.config.hidden_size 
        
        # Simple head mapping directly from CLS token (No LAN, No Taxonomy Head)
        self.binary_head = nn.Sequential(
            nn.Linear(hidden_size, hidden_size),
            nn.GELU(),
            nn.Dropout(0.2),
            nn.Linear(hidden_size, 1)
        )
        
        nn.init.constant_(self.binary_head[-1].weight, 0)
        nn.init.constant_(self.binary_head[-1].bias, 0)

    def forward(self, input_ids, attention_mask):
        outputs = self.deberta(input_ids=input_ids, attention_mask=attention_mask)
        cls_token = outputs.last_hidden_state[:, 0, :]        
        binary_logits = self.binary_head(cls_token).squeeze(-1)
        return binary_logits # Only returning binary logits

