def run_ablation():
    print("--- STARTING ABLATION STUDY (NO LAN, NO MTL) ---")
    device = torch.device('cuda' if torch.cuda.is_available() else 'cpu')
    
    # Use your previously tuned Optuna hyperparameters
    optuna_path = '/vol/bitbucket/hc1721/nlp_scratch/optuna_study/best_hyperparameters.json'
    with open(optuna_path, 'r') as f:
        best_params = json.load(f)
        
    BEST_LR = best_params['lr']
    BEST_WD = best_params['weight_decay']
    BEST_WARMUP = best_params['warmup_ratio']
    BEST_KL = best_params['kl_alpha']
    
    data_path = os.path.join(project_root, 'data', 'dontpatronizeme_pcl.tsv')
    cat_path = os.path.join(project_root, 'data', 'dontpatronizeme_categories.tsv')
    
    train_loader_base, _, _ = get_dataloader(data_path, cat_path, batch_size=16)
    train_dataset_strictly_isolated = train_loader_base.dataset
    
    tokenizer = AutoTokenizer.from_pretrained("microsoft/deberta-v3-base")
    data_collator = DataCollatorWithPadding(tokenizer=tokenizer)
    
    labels = np.array([train_dataset_strictly_isolated[i]['labels'].item() if isinstance(train_dataset_strictly_isolated[i]['labels'], torch.Tensor) else int(train_dataset_strictly_isolated[i]['labels']) for i in range(len(train_dataset_strictly_isolated))])
    
    skf = StratifiedKFold(n_splits=5, shuffle=True, random_state=42)
    fold_metrics = {}

    # --- TRAIN 5 FOLDS ---
    for fold, (train_idx, val_idx) in enumerate(skf.split(np.zeros(len(labels)), labels)):
        print(f"\n================ FOLD {fold + 1}/5 ================")
        train_sub = Subset(train_dataset_strictly_isolated, train_idx)
        val_sub = Subset(train_dataset_strictly_isolated, val_idx)
        
        train_labels = labels[train_idx].astype(int)
        class_counts = np.bincount(train_labels)
        class_weights = 1.0 / class_counts
        sample_weights = [class_weights[l] for l in train_labels]
        sampler = WeightedRandomSampler(weights=sample_weights, num_samples=len(sample_weights), replacement=True)
        
        train_loader = DataLoader(train_sub, batch_size=16, sampler=sampler, collate_fn=data_collator)
        val_loader = DataLoader(val_sub, batch_size=16, shuffle=False, collate_fn=data_collator)
        
        model = PCLModelAblation().float().to(device)
        grouped_params = get_optimizer_grouped_parameters_ablation(model, base_lr=BEST_LR, weight_decay=BEST_WD)
        optimizer = torch.optim.AdamW(grouped_params)
        criterion_binary = nn.BCEWithLogitsLoss()
        
        epochs = 30
        total_steps = len(train_loader) * epochs
        scheduler = get_cosine_schedule_with_warmup(optimizer, num_warmup_steps=int(total_steps * BEST_WARMUP), num_training_steps=total_steps)
        early_stopping = EarlyStopping(patience=3, delta=0.01)
        best_f1, best_thresh = 0.0, 0.0
        
        for epoch in range(epochs):
            model.train()
            loop = tqdm(train_loader, desc=f"Fold {fold+1} Epoch {epoch+1}")
            for batch in loop:
                input_ids, attention_mask = batch['input_ids'].to(device), batch['attention_mask'].to(device)
                b_labels = batch['labels'].to(device).float()
                
                optimizer.zero_grad()
                b_logits1 = model(input_ids, attention_mask)
                b_logits2 = model(input_ids, attention_mask)
                
                loss_binary = 0.5 * (criterion_binary(b_logits1, b_labels) + criterion_binary(b_logits2, b_labels))
                loss_kl = compute_kl_loss(b_logits1, b_logits2)
                loss = loss_binary + (BEST_KL * loss_kl) # No MTL Loss!
                
                loss.backward()
                torch.nn.utils.clip_grad_norm_(model.parameters(), max_norm=0.5)
                optimizer.step()
                scheduler.step()
                loop.set_postfix(loss=loss.item())
        
            model.eval()
            all_logits, all_labels = [], []
            with torch.no_grad():
                for batch in val_loader:
                    logits = model(batch['input_ids'].to(device), batch['attention_mask'].to(device))
                    all_logits.extend(logits.cpu().numpy())
                    all_labels.extend(batch['labels'].numpy())
                    
            all_logits, all_labels = np.array(all_logits), np.array(all_labels)
            epoch_best_f1, epoch_best_thresh = 0.0, 0.0
            for thresh in np.arange(-2.0, 4.0, 0.1):
                preds = (all_logits > thresh).astype(int)
                f1 = f1_score(all_labels, preds, zero_division=0)
                if f1 > epoch_best_f1:
                    epoch_best_f1, epoch_best_thresh = f1, thresh
            
            if epoch_best_f1 > best_f1:
                best_f1, best_thresh = epoch_best_f1, epoch_best_thresh
                # Save isolated model
                torch.save(model.state_dict(), os.path.join(ABLATION_DIR, f'model_fold_{fold+1}.pth'))
                
            early_stopping(epoch_best_f1)
            if early_stopping.early_stop:
                break
                
        fold_metrics[f"Fold_{fold+1}"] = {"Threshold": float(best_thresh), "F1": float(best_f1)}

    # Save isolated thresholds
    with open(os.path.join(ABLATION_DIR, 'ablation_thresholds.json'), 'w') as f:
        json.dump(fold_metrics, f, indent=4)

    # --- ENSEMBLE EVALUATION ON DEV SET ---
    print("\n--- RUNNING ABLATION ENSEMBLE INFERENCE ---")
    raw_df = pd.read_csv(data_path, sep='\t', skiprows=4, header=None, names=['par_id', 'art_id', 'keyword', 'country', 'text', 'label'], quoting=csv.QUOTE_NONE)
    raw_df['par_id'] = raw_df['par_id'].astype(str)
    raw_df['binary_label'] = (raw_df['label'] >= 2).astype(int)
    
    dev_split_path = os.path.join(project_root, 'data', 'practice-splits', 'dev_semeval_parids-labels.csv')
    dev_split_df = pd.read_csv(dev_split_path)
    dev_split_df['par_id'] = dev_split_df['par_id'].astype(str)
    
    dev_df = pd.merge(dev_split_df[['par_id']], raw_df[['par_id', 'text', 'binary_label']], on='par_id', how='left')
    dev_df['text'] = dev_df['text'].apply(clean_text)
    true_labels = dev_df['binary_label'].fillna(0).astype(int).tolist()
    
    dev_dataset = UnlabeledPCLDataset(dev_df, tokenizer)
    dev_loader = DataLoader(dev_dataset, batch_size=32, shuffle=False, collate_fn=data_collator)
    
    all_fold_preds = []  
    model = PCLModelAblation().float().to(device)
    
    for fold in range(1, 6):
        # Load isolated model
        model.load_state_dict(torch.load(os.path.join(ABLATION_DIR, f'model_fold_{fold}.pth'), map_location=device))
        model.eval()
        thresh = fold_metrics[f'Fold_{fold}']['Threshold']
        fold_preds = []
        with torch.no_grad():
            for batch in dev_loader:
                logits = model(batch['input_ids'].to(device), batch['attention_mask'].to(device)).flatten().cpu().numpy()
                fold_preds.extend((logits > thresh).astype(int).tolist())
        all_fold_preds.append(fold_preds)

    hard_ensemble_preds = (np.sum(np.array(all_fold_preds), axis=0) >= 3).astype(int)
    final_ablation_f1 = f1_score(true_labels, hard_ensemble_preds, pos_label=1, average='binary')
    
    print("\n========================================")
    print("      ABLATION RESULTS (NO LAN/MTL)      ")
    print("========================================")
    print(f"Final Ablation F1 Score: {final_ablation_f1:.4f}")
    print("========================================\n")

if __name__ == "__main__":
    run_ablation()